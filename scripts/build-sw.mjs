// Writes dist/sw.js after a build.
//
// canonote's notes live in this browser, so the one thing it must not need is the
// network. Without a service worker the notebooks survive a reload and the app
// itself does not: the shell is fetched from the server every time, and an offline
// reload lands on the browser's error page with the notes intact and unreachable.
//
// The cache is versioned by the content of the build, so a new deploy drops the
// previous one instead of mixing two shells. API calls are never cached: a stale
// answer from /api/notes would be worse than an honest failure.
import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const DIST = new URL("../dist/", import.meta.url).pathname;
const SKIP_DIRS = new Set(["demo"]);

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      out.push(...(await walk(full)));
    } else {
      out.push(full);
    }
  }
  return out;
}

const files = await walk(DIST);
const urls = [];
for (const file of files) {
  const rel = relative(DIST, file).split(sep).join("/");
  if (rel === "sw.js") continue;
  if (/\.(map|log)$/.test(rel)) continue;
  // Every page a person can land on, so an offline reload of any of them works.
  urls.push(`/${rel}`);
}
urls.sort();

const hash = createHash("sha256");
for (const url of urls) {
  const file = join(DIST, url);
  hash.update(url);
  const info = await stat(file);
  hash.update(String(info.size));
}
const version = hash.digest("hex").slice(0, 12);

const worker = `// Generated by scripts/build-sw.mjs — do not edit by hand.
const VERSION = "canonote-${version}";
const PRECACHE = ${JSON.stringify(urls, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(VERSION)
      .then(async (cache) => {
        await cache.addAll(PRECACHE);
        // The routes a person actually types or reloads. The files above are
        // app.html and index.html; these are the URLs that serve them, and a
        // cache key is the URL, so they have to be stored under their own names.
        await cache.addAll(["/app", "/"]);
      })
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((key) => key !== VERSION).map((key) => caches.delete(key))),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  // Never serve a cached API answer: a note read from yesterday's cache would be
  // a lie about what is stored.
  if (url.pathname.startsWith("/api/")) return;

  event.respondWith(
    (async () => {
      const cached = await caches.match(request, { ignoreSearch: true });
      if (cached) return cached;
      try {
        const response = await fetch(request);
        if (response.ok && response.type === "basic") {
          const cache = await caches.open(VERSION);
          cache.put(request, response.clone());
        }
        return response;
      } catch (error) {
        // A failed navigation falls back to the page it meant, not to a bare
        // error page: the notes are here, so the notebook has to open.
        if (request.mode === "navigate") {
          const page = url.pathname.startsWith("/app") ? "/app" : "/";
          const fallback = await caches.match(page, { ignoreSearch: true });
          if (fallback) return fallback;
        }
        throw error;
      }
    })(),
  );
});
`;

await writeFile(join(DIST, "sw.js"), worker);
console.log(`wrote dist/sw.js — ${urls.length} files, ${version}`);
